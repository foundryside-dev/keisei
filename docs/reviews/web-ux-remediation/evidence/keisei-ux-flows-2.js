async (page) => {
  const checks=[]
  const check=(ok,name)=>{if(!ok)throw new Error(name);checks.push(name)}
  await page.goto('http://127.0.0.1:8765/?view=showcase&match=1&ply=5')
  await page.getByText('Replay · ply 5',{exact:true}).waitFor()
  check((await page.locator('.commentary').innerText()).includes('Estimate unavailable'),'Malformed estimate is unavailable in archived replay')
  check(await page.getByRole('group',{name:'Playback speed',exact:true}).locator('button:disabled').count()===3,'Archived playback speed is disabled')
  await page.reload();await page.getByText('Replay · ply 5',{exact:true}).waitFor()
  checks.push('Production saved-match root query reload preserves actualply')
  await page.goto('http://127.0.0.1:8765/?view=showcase&match=2&ply=2')
  await page.getByText('Replay · ply 2',{exact:true}).waitFor()
  check((await page.locator('.commentary').innerText()).includes('Estimate unavailable'),'Legacy estimates unavailable')
  await page.goto('http://127.0.0.1:8765/?view=showcase&match=1&ply=999')
  await page.getByText(/Ply 999 is outside this match/).waitFor();checks.push('Out-of-range storedply explains clamp')
  await page.goto('http://127.0.0.1:8765/?view=showcase&match=999999')
  await page.getByText(/Match 999999 is unavailable/).waitFor();checks.push('Missing saved match offers recovery')
  await page.getByRole('button',{name:'Watch latest match',exact:true}).click()
  await page.getByRole('button',{name:'Pause following',exact:true}).waitFor();checks.push('Missing-match recovery follows latest')
  await page.goto('http://127.0.0.1:8765/?view=league')
  await page.getByRole('heading',{name:/Elo Leaderboard/}).waitFor()
  await page.getByRole('combobox',{name:'Player',exact:true}).selectOption('2')
  check((await page.locator('.record-list').innerText()).includes('#2') && (await page.locator('.record-list').innerText()).includes('Record from'),'Filter exposes stable ID and perspective')
  for(let i=0;i<10;i++)await page.getByRole('button',{name:'Load 5 older evaluations',exact:true}).click()
  await page.getByText('End of evaluation history.',{exact:true}).waitFor()
  check(await page.locator('.gauntlet-epoch').count()===51 && await page.locator('.gauntlet-row').count()===255,'Real API reaches51completeepochs/255slots beyond live50')
  const row=page.locator('[data-entry-id="2"]').first()
  await row.focus();await row.press('Enter')
  await page.getByRole('button',{name:'Close entry detail'}).waitFor()
  check(new URL(page.url()).searchParams.get('entry')==='2','Entry opening creates shareable URL')
  await page.getByRole('button',{name:'Close entry detail'}).press('Space')
  check(await row.evaluate(e=>e===document.activeElement),'Native Space close restores originating row')
  await row.press('Enter');await page.getByRole('button',{name:'Close entry detail'}).waitFor();await page.keyboard.press('Escape');check(await row.evaluate(e=>e===document.activeElement),'Explicit entry Escape restores row')
  await page.goBack()
  await page.getByRole('button',{name:'Close entry detail'}).waitFor();checks.push('Browser Back restores entry detail')
  await page.keyboard.press('Escape')
  check(await page.getByRole('heading',{name:/Elo Leaderboard/}).evaluate(e=>e===document.activeElement),'Back-opened entry with no initiating control uses heading fallback')
  return checks
}
