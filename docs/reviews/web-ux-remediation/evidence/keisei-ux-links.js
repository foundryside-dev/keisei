async (page) => {
  const checks=[]
  const check=(ok,name)=>{if(!ok)throw new Error(name);checks.push(name)}
  await page.setViewportSize({width:1440,height:900})
  await page.goto('http://127.0.0.1:8765/?view=showcase&match=1&ply=3&campaign=test#saved')
  await page.getByText('Replay · ply 3',{exact:true}).waitFor()
  await page.context().grantPermissions(['clipboard-read','clipboard-write'],{origin:'http://127.0.0.1:8765'})
  await page.getByRole('button',{name:'Copy link to this position'}).click()
  await page.getByText('Link copied.',{exact:true}).waitFor()
  const link=await page.evaluate(()=>navigator.clipboard.readText())
  check(new URL(link).searchParams.get('ply')==='3'&&link.includes('campaign=test')&&link.endsWith('#saved'),'Clipboard contains actual match/ply and unrelated URL state')
  const context=await page.context().browser().newContext()
  const fresh=await context.newPage()
  await fresh.goto(link)
  await fresh.getByText('Replay · ply 3',{exact:true}).waitFor()
  checks.push('Copied position opens same saved match in fresh browser context')
  await context.close()
  await page.getByRole('button',{name:'Next ply',exact:true}).click()
  check(new URL(page.url()).searchParams.get('ply')==='4','Scrubbing uses actual stored ply')
  await page.getByRole('tab',{name:'League',exact:true}).click()
  await page.getByRole('heading',{name:/Elo Leaderboard/}).waitFor()
  await page.goBack();await page.getByText('Replay · ply 4',{exact:true}).waitFor()
  checks.push('Back restores scrubbed stored position')
  await page.goForward();await page.getByRole('heading',{name:/Elo Leaderboard/}).waitFor()
  checks.push('Forward restores destination view')
  await page.goto('http://127.0.0.1:8765/?view=league&entry=21')
  await page.getByText(/retired/i).first().waitFor();checks.push('Retired entry link remains informative')
  await page.goto('http://127.0.0.1:8765/?view=league&entry=999999')
  await page.getByText(/unavailable/i).first().waitFor();checks.push('Missing entry has recovery')
  await page.goto('http://127.0.0.1:8765/?view=showcase&match=bad')
  await page.getByText(/invalid match/).first().waitFor();checks.push('Malformed identity shows explicit error')
  await page.goto('http://127.0.0.1:8765/?view=about#about-big-idea')
  check(await page.getByRole('tabpanel',{name:'About',exact:true}).count()===1,'About root query and anchor resolve')
  await page.getByRole('tab',{name:'About',exact:true}).focus();await page.keyboard.press('Home')
  await page.getByRole('tabpanel',{name:'Training',exact:true}).waitFor();checks.push('Native tablist Home switches to Training')
  await page.keyboard.press('ArrowRight');await page.getByRole('tabpanel',{name:'League',exact:true}).waitFor();checks.push('Native tablist arrows switch views')
  await page.goto('http://127.0.0.1:8765/?view=league')
  let fail=true
  await page.route('**/api/league/gauntlet?**',route=>fail?route.fulfill({status:503,body:'unavailable'}):route.continue())
  await page.getByRole('button',{name:'Load 5 older evaluations',exact:true}).click()
  await page.getByText(/Could not load older evaluations/).waitFor()
  check(await page.locator('.gauntlet-epoch').count()===5,'Failed history request retains loaded epochs')
  fail=false
  await page.getByRole('button',{name:'Retry loading older evaluations',exact:true}).click()
  await page.getByText('Evaluations · 10 epochs loaded',{exact:true}).waitFor();checks.push('History retry recovers without duplicates')
  await page.unroute('**/api/league/gauntlet?**')
  return checks
}
