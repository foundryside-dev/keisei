async (page) => {
  const checks=[]
  const check=(ok,name)=>{if(!ok)throw new Error(name);checks.push(name)}
  await page.setViewportSize({width:390,height:844})
  await page.goto('http://127.0.0.1:8765/?view=training')
  await page.getByText('connected',{exact:true}).waitFor()
  await page.locator('.compact-games summary').click()
  await page.getByRole('button',{name:/^Game 32,/}).last().click()
  check((await page.locator('#game-panel .game-info').innerText()).includes('Game 32'),'Training lane32 selectable')
  await page.locator('#game-panel .position-text summary').press('Space')
  const position=await page.locator('#game-panel .position-text').innerText()
  check(position.includes('king')&&position.includes('Promoted')&&position.includes('hand:'),'Training same-position text exposes kings/promotion/hands')
  await page.setViewportSize({width:1280,height:800})
  await page.goto('http://127.0.0.1:8765/?view=showcase')
  await page.getByRole('button',{name:'Pause following',exact:true}).waitFor()
  const heat=page.getByRole('button',{name:'Heatmap: Off',exact:true})
  await heat.focus();await heat.press('Space')
  check(await page.getByRole('button',{name:'Heatmap: On',exact:true}).count()===1,'Native Space toggles Heatmap')
  const setup=page.getByRole('button',{name:'Open match setup form'})
  await setup.focus();await setup.press('Space')
  await page.getByRole('combobox',{name:'Black player',exact:true}).waitFor()
  checks.push('Native Space opens New match')
  await page.getByRole('button',{name:'Hide match setup form'}).press('Space')
  const summary=page.locator('.board-side .position-text summary')
  await summary.focus();await summary.press('Space')
  check(await page.locator('.board-side .position-text').evaluate(e=>e.open),'Native Space opens Position as text without pausing')
  check((await page.locator('.viewer-toolbar strong').innerText())==='Live','Disclosure activation retains following')
  await summary.press('Space')
  await page.getByRole('button',{name:'Jump to first stored ply'}).click()
  await page.getByRole('button',{name:'Previous ply',exact:true}).click()
  check(new URL(page.url()).searchParams.get('ply')==='1','Previous clamps at first stored ply')
  await page.locator('.board-side').focus();await page.keyboard.press('Shift+ArrowLeft')
  check(new URL(page.url()).searchParams.get('ply')==='1','ShiftLeft clamps at first stored ply')
  await page.getByRole('button',{name:'Live',exact:true}).click()
  await page.getByRole('button',{name:'Pause following',exact:true}).click()
  check((await page.locator('.viewer-toolbar strong').innerText())==='Paused at ply 12','Pause at latest labels immediately')
  await page.evaluate(()=>{window.scrollTo(0,document.body.scrollHeight);window.__uxScrollBefore=scrollY;window.__uxBoardBefore=document.querySelector('.board-side .board').textContent})
  return checks
}
